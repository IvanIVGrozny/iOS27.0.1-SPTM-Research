#!/usr/bin/env python3
"""
rebase_blob.py — emit a *rebase-corrected* copy of a kext so IDA shows real
pointer constants, plus a symbol-file stub the Symbolicator can absorb.

Why: kernelcache pointers on disk are arm64e chained fixups
(0x8011xxxxxxxxxxxx). IDA's loader applies no rebasing for MH_FILESET
sub-images, so every vtable / sysent / ops-struct pointer reads as garbage.
Fixing that once, offline, is cheaper than fighting it in the disassembler.

Usage:
    python3 rebase_blob.py <kernelcache> <kext-name> <out-dir>

Emits:
    <out-dir>/<kext>.rebased   flat .text+.data with fixups applied
    <out-dir>/<kext>.py         IDA script to import the fixup map
    <out-dir>/<kext>.json       {fileoff: target_vm} fixup map
"""
import struct, sys, os, json
from kc import Kernelcache
from fixups import decode, KERNEL_BASE, KEYS


def emit(kcpath, kextname, outdir):
    kc = Kernelcache(kcpath)
    fs = [f for f in kc.filesets if f['name'] == kextname]
    if not fs:
        print("no such kext: %s" % kextname)
        return 1
    fs = fs[0]
    os.makedirs(outdir, exist_ok=True)

    fixmap = {}
    chunks = []

    for s in kc.kext_segments(fs):
        if 'sections' not in s:
            continue
        for sc in s['sections']:
            if not sc['size']:
                continue
            blob = bytearray(kc.d[sc['offset']:sc['offset'] + sc['size']])
            for i in range(0, len(blob) - 8, 8):
                raw = struct.unpack_from("<Q", blob, i)[0]
                if not (raw >> 63):
                    continue
                if ((raw >> 49) & 3) not in KEYS:
                    continue
                info = decode(raw, KERNEL_BASE)
                if not (KERNEL_BASE <= info['target'] < 0xfffffe000ba20000):
                    continue
                fixmap[sc['addr'] + i] = info['target']
                struct.pack_into("<Q", blob, i, info['target'])
            chunks.append((sc['addr'], bytes(blob)))

    base = fs['vmaddr']
    stem = kextname.replace('/', '_')

    # Emit each section as its own dense file. A single flattened blob would be
    # gigabyte-scale because kext segments are scattered across the whole
    # 0xfffffe0007004000-0xfffffe000ba20000 kernel VA range.
    secdir = os.path.join(outdir, stem)
    os.makedirs(secdir, exist_ok=True)
    idx = []
    for sc_addr, blob in chunks:
        fname = "%#x_%s.bin" % (sc_addr, stem.split('.')[-1])
        open(os.path.join(secdir, fname), 'wb').write(blob)
        idx.append(dict(vmaddr="%#x" % sc_addr, file=fname, size=len(blob)))
    json.dump(idx, open(os.path.join(secdir, "_index.json"), 'w'), indent=1)
    json.dump({hex(k): hex(v) for k, v in sorted(fixmap.items())},
              open(os.path.join(outdir, stem + ".json"), 'w'), indent=1)

    # IDA script to stamp the fixups into the database
    pairs = "\n".join("    (%#x, %#x)," % (k, v) for k, v in sorted(fixmap.items()))
    script = IDASCRIPT.replace("@@NAME@@", kextname)
    script = script.replace("@@N@@", str(len(fixmap)))
    script = script.replace("@@PAIRS@@", pairs)
    with open(os.path.join(outdir, stem + ".py"), 'w') as f:
        f.write(script)

    print("[+] %s" % kextname)
    print("    vmaddr   %#x" % base)
    print("    uuid     %s" % kc.kext_uuid(fs))
    print("    fixups   %d" % len(fixmap))
    print("    sections %s" % secdir)
    return 0


IDASCRIPT = '''# auto-generated by rebase_blob.py for @@NAME@@ (@@N@@ fixups)
import ida_bytes
FIX = [
@@PAIRS@@
]
for ea, tgt in FIX:
    ida_bytes.set_cmt(ea, "-> %#x" % tgt, 0)
print("[rebase] annotated %d fixups for @@NAME@@" % len(FIX))
'''


if __name__ == '__main__':
    sys.exit(emit(sys.argv[1], sys.argv[2], sys.argv[3]))
